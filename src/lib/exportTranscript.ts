import type { Episode, Podcast } from './types'
import { longDate } from './format'
import { sanitizeFilename } from './exportDoc'

// Build a clean, readable plain-text transcript from an episode's segments — the
// thing a reader actually wants to keep or forward. Timestamped, speaker-labelled,
// one block per turn. Plain .txt so it opens anywhere and pastes cleanly.

const RULE = '─'.repeat(60)

export function transcriptToText(episode: Episode, podcast?: Podcast): string {
  const segments = episode.transcript ?? []
  const header = [
    'Munshot — Podcast Transcript',
    '',
    [podcast?.title, episode.title].filter(Boolean).join(' — '),
    longDate(episode.publishedAt),
    ...(podcast?.author ? [podcast.author] : []),
    '',
    RULE,
    '',
  ]
  const body = segments.map((s) => {
    // "[12:34] Speaker 1" header line, then the turn's text on the next line(s).
    const label = [s.timestamp, s.speaker].filter(Boolean).join('  ')
    return `${label}\n${s.text}`.trim()
  })
  const footer = ['', RULE, 'Generated by Munshot · AI podcast intelligence']
  return [...header, ...body, ...footer].join('\n\n').replace(/\n{3,}/g, '\n\n').trim() + '\n'
}

// Trigger a direct .txt download of the transcript.
export function downloadTranscript(episode: Episode, podcast?: Podcast): void {
  const name = sanitizeFilename(`${podcast ? `${podcast.title} — ` : ''}${episode.title} — Transcript`)
  const blob = new Blob([transcriptToText(episode, podcast)], { type: 'text/plain;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${name}.txt`
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 10_000)
}
