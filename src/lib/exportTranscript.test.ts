import { describe, it, expect } from 'vitest'
import { transcriptToText } from './exportTranscript'
import type { Episode, Podcast } from './types'

const episode = {
  title: 'Intel Earnings, AMD Earnings',
  publishedAt: '2026-11-11T00:00:00.000Z',
  transcript: [
    { id: 't0', speaker: 'Speaker 1', role: 'host', timestamp: '0:00', text: 'Welcome to the show.' },
    { id: 't1', speaker: 'Speaker 2', role: 'guest', timestamp: '1:20', text: 'Thanks for having me.' },
  ],
} as unknown as Episode
const podcast = { title: 'Stratechery', author: 'Ben Thompson' } as unknown as Podcast

describe('transcriptToText', () => {
  it('renders a header, each timestamped turn, and a footer', () => {
    const txt = transcriptToText(episode, podcast)
    expect(txt).toContain('Munshot — Podcast Transcript')
    expect(txt).toContain('Stratechery — Intel Earnings, AMD Earnings')
    expect(txt).toContain('Ben Thompson')
    expect(txt).toContain('0:00  Speaker 1')
    expect(txt).toContain('Welcome to the show.')
    expect(txt).toContain('1:20  Speaker 2')
    expect(txt).toContain('Thanks for having me.')
    expect(txt).toContain('Generated by Munshot')
    expect(txt.endsWith('\n')).toBe(true)
  })

  it('still produces a clean file when there is no transcript', () => {
    const empty = { ...episode, transcript: [] } as unknown as Episode
    const txt = transcriptToText(empty, podcast)
    expect(txt).toContain('Munshot — Podcast Transcript')
    expect(txt).toContain('Stratechery — Intel Earnings, AMD Earnings')
  })

  it('omits the speaker label when a segment has none', () => {
    const noSpeaker = {
      ...episode,
      transcript: [{ id: 't0', speaker: '', role: 'host', timestamp: '0:00', text: 'A flat line.' }],
    } as unknown as Episode
    const txt = transcriptToText(noSpeaker, podcast)
    expect(txt).toContain('0:00\nA flat line.')
  })
})
